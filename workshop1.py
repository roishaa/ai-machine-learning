# TASK 1: Read + Display

from PIL import Image
import numpy as np
import matplotlib.pyplot as plt

# 🔁 Change this to your uploaded image file name
filename = "image.jpg"

# Read image using Pillow
img = Image.open(filename)

# Convert to NumPy array
img_array = np.array(img)

# Display original image
plt.imshow(img_array)
plt.title(" Original Image")
plt.axis("off")
plt.show()

print("Image shape:", img_array.shape)  # should be (H, W, 3) for RGB

# TASK 2: Top-left 100x100

top_left = img_array[0:100, 0:100]   # rows 0-99, cols 0-99

plt.imshow(top_left)
plt.title("Top-left 100x100")
plt.axis("off")
plt.show()

# TASK 3: Show RGB channels

R = img_array[:, :, 0]   # Red channel
G = img_array[:, :, 1]   # Green channel
B = img_array[:, :, 2]   # Blue channel

plt.imshow(R, cmap="Reds")
plt.title("R (Red Channel)")
plt.axis("off")
plt.show()

plt.imshow(G, cmap="Greens")
plt.title(" G (Green Channel)")
plt.axis("off")
plt.show()

plt.imshow(B, cmap="Blues")
plt.title(" B (Blue Channel)")
plt.axis("off")
plt.show()

# TASK 4: Modify top 100x100 to 210

modified = img_array.copy()

# Set top-left 100x100 region to 210 (light gray)
modified[0:100, 0:100] = 210

plt.imshow(modified)
plt.title("Modified Image (Top-left 100x100 = 210)")
plt.axis("off")
plt.show()

