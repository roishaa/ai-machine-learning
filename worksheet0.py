def unit_converter(conversion_type, value, direction):
    """
    Converts units of measurement between length, weight, and volume.

    Parameters:
    conversion_type (str): Type of conversion ('length', 'weight', 'volume')
    value (float): Numeric value to convert
    direction (str): Conversion direction

    Returns:
    float: Converted value
    """

    if conversion_type == "length":
        if direction == "m_to_ft":
            return value * 3.28084
        elif direction == "ft_to_m":
            return value / 3.28084

    elif conversion_type == "weight":
        if direction == "kg_to_lbs":
            return value * 2.20462
        elif direction == "lbs_to_kg":
            return value / 2.20462

    elif conversion_type == "volume":
        if direction == "l_to_gal":
            return value * 0.264172
        elif direction == "gal_to_l":
            return value / 0.264172

    else:
        raise ValueError("Unsupported conversion type.")


